<#
.SYNOPSIS
  Copy the maintained native files in mobile/{android,ios} over the projects
  generated by `npx cap add android|ios`.

.DESCRIPTION
  Capacitor regenerates platform projects from templates. Instead of committing
  a full Gradle/Xcode project we keep the handful of files that actually matter
  in this repo and stamp them back after generation:

    android/app/src/main/AndroidManifest.xml   (.md association, permissions)
    android/app/src/main/res/values/styles.xml (immersive status bar)
    android/app/src/main/res/xml/file_paths.xml (FileProvider)
    android/app/src/main/java/vip/zhengl/neom/MainActivity.kt

  iOS cannot be fully merged on Windows (no PlistBuddy); this script then only
  validates that Info.plist contains the .md document types and prints the
  commands to run on macOS.

.PARAMETER Platform
  android | ios | all (default all)

.PARAMETER MobileDir
  Override mobile/ location.

.EXAMPLE
  pwsh scripts/sync-mobile-native.ps1 -Platform android
#>
[CmdletBinding()]
param(
  [ValidateSet('android', 'ios', 'all')]
  [string]$Platform = 'all',
  [string]$MobileDir
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $MobileDir) { $MobileDir = Join-Path $root 'mobile' }

function Write-Step([string]$m) { Write-Host "`n==> $m" -ForegroundColor Cyan }
function Write-Ok([string]$m) { Write-Host "  OK  $m" -ForegroundColor Green }
function Write-Warn2([string]$m) { Write-Host "  !!  $m" -ForegroundColor Yellow }

$androidSrc = Join-Path $MobileDir 'android'
$androidGen = Join-Path $androidSrc 'app\src\main'

function Sync-Android {
  Write-Step 'Syncing Android native files'
  $pkgDir = Join-Path $androidGen 'java\vip\zhengl\neom'
  if (-not (Test-Path $pkgDir)) {
    # cap add android may not have run yet, or the package path differs.
    $candidate = Get-ChildItem (Join-Path $androidGen 'java') -Directory -Recurse -ErrorAction SilentlyContinue |
      Where-Object { $_.Name -eq 'neom' } | Select-Object -First 1
    if ($candidate) { $pkgDir = $candidate.FullName }
  }

  $pairs = @(
    @{ Src = (Join-Path $androidGen 'AndroidManifest.xml'); Dst = (Join-Path $androidGen 'AndroidManifest.xml'); Note = 'AndroidManifest.xml' },
    @{ Src = (Join-Path $androidGen 'res\values\styles.xml'); Dst = (Join-Path $androidGen 'res\values\styles.xml'); Note = 'res/values/styles.xml' },
    @{ Src = (Join-Path $androidGen 'res\xml\file_paths.xml'); Dst = (Join-Path $androidGen 'res\xml\file_paths.xml'); Note = 'res/xml/file_paths.xml' },
    @{ Src = (Join-Path $androidGen 'java\vip\zhengl\neom\MainActivity.kt'); Dst = (Join-Path $pkgDir 'MainActivity.kt'); Note = 'MainActivity.kt' }
  )

  $androidProject = Join-Path $androidSrc 'app\build.gradle'
  if (-not (Test-Path $androidProject)) {
    Write-Warn2 'android/app/build.gradle not found — run `npx cap add android` in mobile/ first.'
    Write-Warn2 'The maintained files are already in mobile/android/app/src/main/ and will be used as-is.'
    return
  }

  foreach ($p in $pairs) {
    if (-not (Test-Path $p.Src)) { Write-Warn2 "missing source: $($p.Note)"; continue }
    if ($p.Src -eq $p.Dst) { Write-Ok "$($p.Note) already in place"; continue }
    $dir = Split-Path -Parent $p.Dst
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    Copy-Item -Path $p.Src -Destination $p.Dst -Force
    Write-Ok "copied $($p.Note)"
  }
}

function Sync-Ios {
  Write-Step 'Checking iOS Info.plist'
  $plist = Join-Path $MobileDir 'ios\App\App\Info.plist'
  if (-not (Test-Path $plist)) {
    Write-Warn2 "Info.plist not found at $plist"
    return
  }
  $text = [System.IO.File]::ReadAllText($plist, [System.Text.Encoding]::UTF8)
  $checks = [ordered]@{
    'CFBundleDocumentTypes'       = $text -match 'CFBundleDocumentTypes'
    'UTImportedTypeDeclarations'  = $text -match 'UTImportedTypeDeclarations'
    'net.daringfireball.markdown' = $text -match 'net\.daringfireball\.markdown'
    'LSSupportsOpeningDocumentsInPlace' = $text -match 'LSSupportsOpeningDocumentsInPlace'
    'UIFileSharingEnabled'        = $text -match 'UIFileSharingEnabled'
    'NSCameraUsageDescription'    = $text -match 'NSCameraUsageDescription'
  }
  foreach ($k in $checks.Keys) {
    if ($checks[$k]) { Write-Ok $k } else { Write-Warn2 "$k MISSING" }
  }
  Write-Host @'

  On macOS, after `npx cap add ios`, merge these keys into the generated plist:
    /usr/libexec/PlistBuddy -c "Merge mobile/ios/App/App/Info.plist" \
      mobile/ios/App/App/Info.plist
  (or copy this file over mobile/ios/App/App/Info.plist when the generated one
   has no custom keys yet), then:  cd mobile/ios/App && pod install
'@ -ForegroundColor DarkGray
}

switch ($Platform) {
  'android' { Sync-Android }
  'ios' { Sync-Ios }
  'all' { Sync-Android; Sync-Ios }
}

Write-Host "`nDone." -ForegroundColor Green
